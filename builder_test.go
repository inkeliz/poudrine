func workerTestConfig(root string) BuilderConfig {
	cfg := DefaultBuilderConfig()
	cfg.ConfigDir = filepath.Join(root, "config")
	cfg.BaseFS = filepath.Join(root, "base")
	cfg.Distfiles = filepath.Join(root, "distfiles")
	cfg.SigningKey = filepath.Join(root, "signing.key")
	cfg.PackagesFile = filepath.Join(root, "origins")
	cfg.StatusFile = filepath.Join(root, "status.json")
	cfg.Release = "15.1-RELEASE"
	return cfg
}

func TestPerPackageMakeJobs(t *testing.T) {
	cfg := workerTestConfig(t.TempDir())
	for _, tc := range []struct {
		number, limit int
		parallel      bool
		fragment      string
	}{
		{8, 4, true, "MAKE_JOBS_NUMBER=8\nMAKE_JOBS_NUMBER_LIMIT=4\n"},
		{0, 3, true, "MAKE_JOBS_NUMBER_LIMIT=3\n"},
		{2, 0, true, "MAKE_JOBS_NUMBER=2\n"},
		{8, 1, false, "MAKE_JOBS_NUMBER=8\nMAKE_JOBS_NUMBER_LIMIT=1\n"},
		{1, 0, false, "MAKE_JOBS_NUMBER=1\n"},
		{0, 0, false, ""},
	} {
		cfg.MakeJobsNumber, cfg.MakeJobsNumberLimit = tc.number, tc.limit
		b := &Builder{cfg: cfg}
		if err := b.configure(); err != nil {
			t.Fatal(err)
		}
		global, err := os.ReadFile(filepath.Join(cfg.ConfigDir, "poudriere.conf"))
		if err != nil || strings.Contains(string(global), "\nALLOW_MAKE_JOBS=yes\n") != tc.parallel {
			t.Fatalf("ALLOW_MAKE_JOBS for %d/%d: %q, %v", tc.number, tc.limit, global, err)
		}
		fragment, err := os.ReadFile(cfg.makeJobsFile())
		if tc.fragment == "" {
			if !os.IsNotExist(err) {
				t.Fatalf("reset left make job overrides: %q, %v", fragment, err)
			}
		} else if err != nil || string(fragment) != "# Generated by Poudrine worker\n"+tc.fragment {
			t.Fatalf("make job overrides for %d/%d: %q, %v", tc.number, tc.limit, fragment, err)
		}
	}
}

func TestWorkerCommands(t *testing.T) {
	root := t.TempDir()
	c := workerTestConfig(root)
	write := func(file, data string, mode os.FileMode) {
		t.Helper()
		if err := os.WriteFile(file, []byte(data), mode); err != nil {
			t.Fatal(err)
		}
	}
	// The stand-in records the exact CLI arguments, including the worker's
	// alternate configuration directory, and models one existing ports tree.
	t.Setenv("POUDRINE_TEST_CALLS", filepath.Join(root, "calls"))
	write(filepath.Join(root, "poudriere"), `#!/bin/sh
echo "$*" >> "$POUDRINE_TEST_CALLS"
shift 3
case "$1 $2" in
"ports -l") echo main ;;
"bulk -j") echo "Building ftp/curl" ;;
esac
`, 0755)
	t.Setenv("PATH", root+":"+os.Getenv("PATH"))
	write(c.PackagesFile, "ftp/curl\n", 0644)
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	b, err := NewBuilder(c, func(context.Context) ([]string, error) {
		return []string{"lang/python", "ftp/curl", "devel/py-pip@py311"}, nil
	}, func(_ context.Context, err error) {
		if err != nil {
			t.Errorf("cycle: %v", err)
		}
		cancel()
	})
	if err != nil {
		t.Fatal(err)
	}
	if err = b.Run(ctx); !errors.Is(err, context.Canceled) {
		t.Fatalf("shutdown: %v", err)
	}
	calls, err := os.ReadFile(filepath.Join(root, "calls"))
	if err != nil {
		t.Fatal(err)
	}
	var want []string
	for _, args := range []string{"jail -l -q -n", "jail -c -j latest -v 15 -m pkgbase=base_release_1 -U https://pkg.FreeBSD.org", "ports -l -q -n", "ports -u -p main", "bulk -j latest -p main -b latest -f " + c.PackagesFile} {
		want = append(want, "-N -e "+c.ConfigDir+" "+args)
	}
	lines := strings.Split(strings.TrimSuffix(string(calls), "\n"), "\n")
	if len(lines) != len(want) {
		t.Fatalf("calls: %s", calls)
	}
	bulkCommand, name, hasName := strings.Cut(lines[len(lines)-1], " -B ")
	if _, err := time.Parse(buildNameFormat, name); !hasName || err != nil {
		t.Fatalf("missing unique bulk name: %s", lines[len(lines)-1])
	}
	lines[len(lines)-1] = bulkCommand
	if strings.Join(lines, "\n") != strings.Join(want, "\n") {
		t.Fatalf("calls: %s", calls)
	}
	s, err := ReadBuildStatus(c.StatusFile)
	if err != nil || s.Stage != "idle" || len(s.Log) != 1 || s.Log[0] != "Building ftp/curl" || s.Finished.Before(s.Started) {
		t.Fatalf("status: %+v %v", s, err)
	}
	got, err := os.ReadFile(c.PackagesFile)
	if err != nil || string(got) != "devel/py-pip@py311\nftp/curl\nlang/python\n" {
		t.Fatalf("origins %s: %v", got, err)
	}
	if _, err = b.syncOrigins([]string{"bad/port\n-x"}); err == nil {
		t.Fatal("accepted a newline in an origin")
	}
	got2, err := os.ReadFile(c.PackagesFile)
	if err != nil || string(got2) != string(got) {
		t.Fatal("invalid request changed exported file")
	}
}

func TestInstalledPoudriereLists(t *testing.T) {
	if _, err := exec.LookPath("poudriere"); err != nil {
		t.Skip("poudriere is not installed")
	}
	c := workerTestConfig(t.TempDir())
	b, err := NewBuilder(c, func(context.Context) ([]string, error) { return nil, nil }, nil)
	if err != nil {
		t.Fatal(err)
	}
	if err = b.configure(); err != nil {
		t.Fatal(err)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	for _, kind := range []string{"jail", "ports"} {
		list, err := b.command(ctx, true, kind, "-l", "-q", "-n")
		if err != nil {
			t.Fatalf("%s: %v, log %v", kind, err, b.Status().Log)
		}
		if strings.TrimSpace(list) != "" {
			t.Fatalf("expected empty %s list in isolated configuration, got %s", kind, list)
		}
	}
}
